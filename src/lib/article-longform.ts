function detectProvince(text: string) {
	const normalized = text.toLowerCase();
	return provinceMatchers.find((entry) => entry.patterns.some((pattern) => normalized.includes(pattern.toLowerCase())))?.name;
}

function detectProduct(text: string) {
	const normalized = text.toLowerCase();
	return productConfigs.find((entry) => entry.patterns.some((pattern) => normalized.includes(pattern.toLowerCase())))?.config ?? defaultConfig;
}

export function buildArticleLongform(title: string, slug: string, canonicalPath?: string): LongformConfig {
	const source = `${title} ${slug}`;
	const product = detectProduct(source);
	const province = detectProvince(source);
	const locationContext = province ?? 'ลูกค้าทั่วประเทศ';
	const audience = province
		? `คนที่กำลังจะขาย${product.label}ใน${province}`
		: `คนที่กำลังจะขาย${product.label}และต้องการเช็กราคาแบบไม่เสียเวลา`;
	const internalLinks: LinkItem[] = [
		{ href: product.hubHref, label: product.hubLabel },
		{ href: '/เช็กราคาก่อนขาย/', label: 'เช็กราคาก่อนขาย' },
		{ href: '/ราคากลางรับซื้อ/', label: 'ดูปัจจัยราคากลางรับซื้อ' },
		{ href: '/คู่มือก่อนขาย/', label: 'คู่มือก่อนขายทั้งหมด' },
	];

	if (province) {
		internalLinks.push({ href: '/พื้นที่ให้บริการ/', label: `แนวทางนัดรับและพื้นที่ให้บริการสำหรับ${province}` });
	}

	if (canonicalPath && canonicalPath.startsWith('/') && canonicalPath !== `/${slug}/`) {
		internalLinks.unshift({ href: canonicalPath, label: 'ดูหน้าหลักที่เกี่ยวข้องโดยตรง' });
	}

	return {
		theme: title,
		audience,
		locationContext,
		emphasis: product.emphasis,
		prepareItems: product.prepareItems,
		valueFactors: product.valueFactors,
		commonMistakes: product.commonMistakes,
		internalLinks,
		density: 'full',
	};
}
