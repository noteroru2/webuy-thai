function md(slug, title, description, body, faqs = [], heroImage = '') {
  const faqYaml = faqs.map(f =>
    `  - question: "${f.q.replace(/"/g, "'")}"\n    answer: "${f.a.replace(/"/g, "'")}"`
  ).join('\n');
  const hero = heroImage ? `\nheroImage: "${heroImage}"` : '';
  return `---
title: "${title}"
description: "${description}"
pubDate: "${TODAY}"
updatedDate: "${TODAY}"
slug: "${slug}"
qualityScore: 8
qualityFlags: []${hero}
faqItems:
${faqYaml}
---

${body}
`;
}

