export function hashSlug(slug = '') {
	let h = 2166136261;
	for (let i = 0; i < slug.length; i++) {
		h ^= slug.charCodeAt(i);
		h = Math.imul(h, 16777619);
	}
	return h >>> 0;
}

export function pick(pool, seed, salt = 0) {
	if (!pool?.length) return '';
	return pool[(seed + salt) % pool.length];
}

export function pickMany(pool, seed, count) {
	return [...pool]
		.map((item, i) => ({ item, sort: hashSlug(`${seed}:${i}:${item.question}`) }))
		.sort((a, b) => a.sort - b.sort)
		.slice(0, count)
		.map((x) => x.item);
}

export function interpolate(template, vars) {
	return String(template).replace(/\{(\w+)\}/g, (_, key) => vars[key] ?? '');
}
